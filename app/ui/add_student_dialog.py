from PyQt6.QtCore import Qt, QDate
from PyQt6.QtWidgets import (
    QCheckBox,
    QComboBox,
    QDateEdit,
    QDialog,
    QDialogButtonBox,
    QFormLayout,
    QHBoxLayout,
    QLabel,
    QLineEdit,
    QMessageBox,
    QPlainTextEdit,
    QVBoxLayout,
)


class AddStudentDialog(QDialog):
    """
    Dialog for registering a new student.
    
    Supports both automatic sequential admission number generation and
    manual/custom admission number entry.
    """

    def __init__(self, batches, parent=None, default_admission_number: str | None = None):
        """
        Initialize the AddStudentDialog.

        Args:
            batches: Iterable of active Batch model instances to populate dropdown.
            parent: Parent QWidget.
            default_admission_number: Suggested autogenerated admission number (e.g., 'ADM-2026-0001').
        """
        super().__init__(parent)

        self.setWindowTitle("Add Student")
        self.setMinimumWidth(500)
        self._suggested_admission_number = default_admission_number or ""

        layout = QVBoxLayout(self)
        layout.setContentsMargins(25, 25, 25, 25)
        layout.setSpacing(18)

        # Header
        self.title_label = QLabel("Add Student")
        self.title_label.setObjectName("addStudentTitle")

        self.subtitle_label = QLabel(
            "Enter the student's personal and parent information."
        )
        self.subtitle_label.setObjectName("addStudentSubtitle")

        layout.addWidget(self.title_label)
        layout.addWidget(self.subtitle_label)

        # Form
        form = QFormLayout()
        form.setSpacing(12)
        form.setFieldGrowthPolicy(QFormLayout.FieldGrowthPolicy.ExpandingFieldsGrow)
        form.setRowWrapPolicy(QFormLayout.RowWrapPolicy.DontWrapRows)
        form.setLabelAlignment(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter)

        # Admission Number input field
        self.admission_number_input = QLineEdit()
        self.admission_number_input.setPlaceholderText("e.g. ADM-2026-0001")

        # Checkbox allowing the user to switch between automatic generation and custom entry
        self.auto_generate_admission_cb = QCheckBox("Auto-generate")
        self.auto_generate_admission_cb.setCursor(Qt.CursorShape.PointingHandCursor)
        self.auto_generate_admission_cb.setStyleSheet("""
            QCheckBox {
                color: #012D54;
                font-weight: 500;
                font-size: 13px;
            }
        """)

        # Connect toggle action to handler
        self.auto_generate_admission_cb.toggled.connect(self._on_auto_generate_toggled)

        # Container row layout for admission number input + Auto-generate toggle
        admission_row_layout = QHBoxLayout()
        admission_row_layout.setContentsMargins(0, 0, 0, 0)
        admission_row_layout.setSpacing(10)
        admission_row_layout.addWidget(self.admission_number_input, 1)
        admission_row_layout.addWidget(self.auto_generate_admission_cb)

        # Set initial state: default to Auto-generate if a suggested number was provided
        if self._suggested_admission_number:
            self.auto_generate_admission_cb.setChecked(True)
            self.admission_number_input.setText(self._suggested_admission_number)
            self.admission_number_input.setReadOnly(True)
            self.admission_number_input.setStyleSheet("background-color: #F8F6EA; color: #012D54;")
        else:
            self.auto_generate_admission_cb.setChecked(False)


        self.first_name_input = QLineEdit()
        self.first_name_input.setPlaceholderText(
            "First name"
        )

        self.last_name_input = QLineEdit()
        self.last_name_input.setPlaceholderText(
            "Last name"
        )

        self.parent_name_input = QLineEdit()
        self.parent_name_input.setPlaceholderText(
            "Parent / guardian name"
        )

        self.parent_phone_input = QLineEdit()
        self.parent_phone_input.setPlaceholderText(
            "Phone number"
        )

        self.whatsapp_input = QLineEdit()
        self.whatsapp_input.setPlaceholderText(
            "WhatsApp number"
        )

        self.batch_input = QComboBox()

        for batch in batches:
            self.batch_input.addItem(
                batch.name,
                batch.id,
            )

        self.date_of_birth_input = QDateEdit()
        self.date_of_birth_input.setCalendarPopup(True)
        self.date_of_birth_input.setDisplayFormat("dd/MM/yyyy")
        self.date_of_birth_input.setSpecialValueText("Date of birth")
        self.date_of_birth_input.setMinimumDate(
            QDate(1900, 1, 1)
        )
        self.date_of_birth_input.setDate(
            self.date_of_birth_input.minimumDate()
        )

        self.school_input = QLineEdit()
        self.school_input.setPlaceholderText(
            "School name"
        )

        self.admission_date_input = QDateEdit()
        self.admission_date_input.setCalendarPopup(True)
        self.admission_date_input.setDisplayFormat("dd/MM/yyyy")
        self.admission_date_input.setDate(QDate.currentDate())

        self.monthly_fee_input = QLineEdit()
        self.monthly_fee_input.setPlaceholderText(
            "Optional monthly fee (overrides batch rate)"
        )

        self.status_input = QComboBox()
        self.status_input.addItems([
            "ACTIVE",
            "INACTIVE",
            "LEFT",
        ])

        self.notes_input = QPlainTextEdit()
        self.notes_input.setPlaceholderText(
            "Additional notes..."
        )
        self.notes_input.setMaximumHeight(90)

        # Helper for required field labels with red accent
        def req(label_text: str) -> QLabel:
            lbl = QLabel(f"{label_text} <span style='color: #DC2626; font-weight: bold;'>*</span>")
            lbl.setTextFormat(Qt.TextFormat.RichText)
            return lbl

        # Row for admission number with auto-generate option
        form.addRow("Admission No.", admission_row_layout)
        form.addRow(req("First Name"), self.first_name_input)
        form.addRow("Last Name", self.last_name_input)
        form.addRow(req("Parent Name"), self.parent_name_input)
        form.addRow("Parent Phone", self.parent_phone_input)
        form.addRow("WhatsApp Number", self.whatsapp_input)
        form.addRow(req("Batch"), self.batch_input)
        form.addRow("Monthly Fee (₹)", self.monthly_fee_input)
        form.addRow("Date of Birth", self.date_of_birth_input)
        form.addRow("School", self.school_input)
        form.addRow("Admission Date", self.admission_date_input)
        form.addRow("Status", self.status_input)
        form.addRow("Notes", self.notes_input)

        layout.addLayout(form)

        # Buttons
        buttons = QDialogButtonBox(
            QDialogButtonBox.StandardButton.Cancel
            | QDialogButtonBox.StandardButton.Save
        )

        save_btn = buttons.button(QDialogButtonBox.StandardButton.Save)
        cancel_btn = buttons.button(QDialogButtonBox.StandardButton.Cancel)
        if save_btn:
            save_btn.setObjectName("primaryDialogButton")
            save_btn.setCursor(Qt.CursorShape.PointingHandCursor)
        if cancel_btn:
            cancel_btn.setObjectName("secondaryDialogButton")
            cancel_btn.setCursor(Qt.CursorShape.PointingHandCursor)

        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)

        layout.addWidget(buttons)

    def accept(self) -> None:
        if self.batch_input.count() == 0 or self.batch_input.currentData() is None:
            QMessageBox.warning(
                self,
                "No Batches Available",
                "Please create at least one batch before registering students.",
            )
            return
        super().accept()

    def _on_auto_generate_toggled(self, checked: bool) -> None:
        """
        Handle toggling between autogenerated admission numbers and custom entry.
        
        When checked:
            - Displays the autogenerated/suggested admission number.
            - Sets the text input to read-only with a subtle read-only style.
        When unchecked:
            - Allows the user to freely type any custom admission number.
            - Restores normal editable styling.
        """
        if checked:
            if self._suggested_admission_number:
                self.admission_number_input.setText(self._suggested_admission_number)
            self.admission_number_input.setReadOnly(True)
            self.admission_number_input.setStyleSheet("background-color: #F8F6EA; color: #012D54;")
        else:
            self.admission_number_input.setReadOnly(False)
            self.admission_number_input.setStyleSheet("")
            self.admission_number_input.setFocus()

    def set_suggested_admission_number(self, admission_number: str) -> None:
        """
        Update the autogenerated admission number suggestion dynamically.

        Args:
            admission_number: The next sequential admission number string.
        """
        self._suggested_admission_number = admission_number
        if self.auto_generate_admission_cb.isChecked():
            self.admission_number_input.setText(admission_number)